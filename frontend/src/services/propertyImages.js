// Helper to get unique images for any property ID
export const getUniquePropertyImages = (propertyId, fallbackTitle = '') => {
  if (PROPERTY_IMAGES_MAP[propertyId]) {
    return PROPERTY_IMAGES_MAP[propertyId];
  }

  // Generate deterministic hash from property ID or Title
  const str = propertyId || fallbackTitle || 'prop_default';
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  const idx = Math.abs(hash) % UNIQUE_IMAGE_POOL.length;
  const img1 = UNIQUE_IMAGE_POOL[idx];
  const img2 = UNIQUE_IMAGE_POOL[(idx + 7) % UNIQUE_IMAGE_POOL.length];
  const img3 = UNIQUE_IMAGE_POOL[(idx + 13) % UNIQUE_IMAGE_POOL.length];

  return [img1, img2, img3];
};
